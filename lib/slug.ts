/**
 * Транслітерація назв файлів у веб-адреси.
 *
 * Decap CMS не вміє транслітерувати українську: створюючи новину
 * «Новий семінар», він назве файл `2026-07-26-новий-семінар.md`. Next не
 * зіставляє такий кириличний шлях зі згенерованим маршрутом — сторінка
 * потрапляє в список новин, але за посиланням віддає 404. Тобто редактор
 * побачив би публікацію на сайті, а читачі — ні.
 *
 * Тому адреса будується з назви файлу тут, а не береться дослівно.
 * Для вже наявних файлів (їх іменувала міграція латиницею) перетворення
 * нічого не змінює.
 *
 * Таблиця збігається з тією, за якою слаги створювала міграція
 * (scripts/migrate.mjs), щоб адреси лишалися ті самі.
 */
const SLUG_MAP: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "h", ґ: "g", д: "d", е: "e", є: "ie", ж: "zh", з: "z",
  и: "y", і: "i", ї: "i", й: "i", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p",
  р: "r", с: "s", т: "t", у: "u", ф: "f", х: "kh", ц: "ts", ч: "ch", ш: "sh",
  щ: "shch", ь: "", ю: "iu", я: "ia", ё: "e", ы: "y", э: "e", ъ: "",
}

export function slugify(input: string): string {
  const out = [...input.toLowerCase()]
    .map((c) => (c in SLUG_MAP ? SLUG_MAP[c] : c))
    .join("")
    .replace(/['’"«»]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
  return out || "storinka"
}
